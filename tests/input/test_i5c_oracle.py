#!/usr/bin/env python3
"""Independent numeric/byte/context controls for the draft W0 generator only."""
import copy
import json
from pathlib import Path
import struct
import unittest
import importlib.util
_spec=importlib.util.spec_from_file_location('i5c_oracle',Path(__file__).resolve().parent/'fixtures/make_i5c.py')
oracle=importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(oracle)


class OracleControls(unittest.TestCase):
    def setUp(self):
        self.records=oracle.artifacts()
        self.cases={row['name']:row for row in self.records['manifest.json']['cases']}

    def test_named_matrix_has_complete_unique_inventory(self):
        self.assertEqual(len(self.cases),140)
        self.assertEqual([len(oracle.BINDING_NEGATIVES),len(oracle.SERIALIZATION_NEGATIVES),
                          len(oracle.CLI_NEGATIVES),len(oracle.MUTATIONS)],[19,24,12,24])
        self.assertEqual(len(self.records['performance.json']['fixtureCases']),10)
        self.assertEqual(len(self.records['owned-captures.json']['cases']),8)
        self.assertEqual(self.records['qualification-matrix.json']['legacy_outputs']['total'],666)

    def test_integer_boundary_expectations_do_not_reuse_expected_function(self):
        # Explicit constants are independent of expected()/divmod().
        examples={
            'mov32mi-upper':('18446744073709551624',1,8,'consistent_with_evidence'),
            'mov32mi-upper-boundary':('18446744073709551616',1,0,'consistent_with_evidence'),
            'mov32mi-negative-zero':('0',0,0,'refuted_under_premises'),
            'mov32mi-negative-nonzero':('8',0,8,'refuted_under_premises'),
            'mov32mi-underflow':('-8',-1,18446744073709551608,'unknown'),
            'lower-disp32-min':('-2147483648',-1,18446744071562067968,'unknown'),
            'mov32mi-disp8-min':('0',0,0,'refuted_under_premises'),
            'mov32mi-disp8-max':('18446744073709551616',1,0,'consistent_with_evidence'),
            'mov32mi-disp32-min':('0',0,0,'refuted_under_premises'),
            'mov32mi-disp32-max':('18446744075857035262',1,2147483646,'consistent_with_evidence'),
        }
        for name,(total,q,address,conclusion) in examples.items():
            with self.subTest(name=name):
                expected=self.cases[name]['expected']
                kernel=expected['arithmetic_diagnostic']
                self.assertEqual((kernel['T'],kernel['q'],int(kernel['EA'],16),expected['conclusion']),
                                 (total,q,address,conclusion))

    def test_six_independently_written_machine_productions(self):
        # Direct reviewed byte vectors, not generated by encoding().
        vectors=[('MOV32mi','c7401005000000',32,1),
                 ('MOV64mi32','48c7401005000000',64,1),
                 ('MOV32rm','8b4010',32,0),('MOV64rm','488b4010',64,0),
                 ('MOV32mr','894010',32,1),('MOV64mr','48894010',64,1)]
        for name,code,width,operation in vectors:
            with self.subTest(form=name):
                receipt=oracle.inspect_encoding(code)
                self.assertEqual((receipt['opcode'],receipt['base'],receipt['index'],
                    receipt['signed_displacement'],receipt['displacement_width'],
                    receipt['access_width'],receipt['operation']),
                    (name,'rax',None,16,8,width,operation))
                self.assertEqual(self.cases[name.lower()+'-upper']['code'],code)

    def test_sib_rex_displacement_and_excluded_physical_tuples(self):
        special={
            'rsp-sib-upper':('MOV32mi','rsp',None,1,16,32,1),
            'rbp-zero-disp8':('MOV32mi','rbp',None,1,0,32,1),
            'r12-sib-upper':('MOV32mi','r12',None,1,16,32,1),
            'r13-upper':('MOV32mi','r13',None,1,16,32,1),
            'indexed-nonzero':('MOV32mi','rax','rcx',2,16,32,1),
            'rip-relative':('MOV64rm','rip',None,1,16,64,0),
            'operand-size':('MOV16mi','rax',None,1,16,16,1),
            'vector':('MOVUPSmr','rax',None,1,0,128,1),
        }
        for name,tuple_expected in special.items():
            with self.subTest(case=name):
                receipt=self.cases[name]['decoded_receipt']
                self.assertEqual(tuple(receipt[key] for key in ('opcode','base','index','scale',
                    'signed_displacement','access_width','operation')),tuple_expected)
        self.assertEqual(int(self.cases['indexed-nonzero']['actual_effective_address'],16),26)
        self.assertEqual(int(self.cases['rip-relative']['actual_effective_address'],16),0x401017)
        self.assertIsNone(self.cases['indexed-nonzero']['expected']['arithmetic'])
        self.assertEqual(self.cases['indexed-nonzero']['reported'],'0x000000000000001a')

    def test_payload_register_alias_and_payload_independence_are_explicit(self):
        aliased=self.cases['mov32mr-upper']
        self.assertEqual(aliased['decoded_receipt']['payload_register'],'rax')
        self.assertEqual(aliased['payload'],4294967288)
        a,b=[self.cases[name] for name in ('payload-register-zero','payload-register-nonzero')]
        self.assertEqual(a['expected']['arithmetic'],b['expected']['arithmetic'])
        self.assertNotEqual(a['registers']['rcx'],b['registers']['rcx'])
        self.assertEqual(a['registers']['rax'],b['registers']['rax'])

    def test_readiness_and_inclusive_exclusive_span_boundaries(self):
        for name in ('span-end-h32','span-end-h64','reported-last32','reported-last64'):
            self.assertEqual(self.cases[name]['expected']['conclusion'],'refuted_under_premises'
                             if name.startswith('span-end') else 'consistent_with_evidence')
        for name in ('span-cross-h32','span-cross-h64','span-wrap32','span-wrap64',
                     'reported-before','reported-after32','reported-after64'):
            self.assertEqual(self.cases[name]['expected']['conclusion'],'unknown')
            self.assertIsNotNone(self.cases[name]['expected']['arithmetic'])
        for name in ('missing-integer','wrong-operation','missing-decoded-receipt',
                     'decoder-bap-base-disagreement','decoder-bap-constant-disagreement'):
            self.assertEqual(self.cases[name]['expected']['conclusion'],'unknown')
            self.assertIsNone(self.cases[name]['expected']['arithmetic'])

    def test_budget_boundaries_and_atomic_derived_claims(self):
        ordinary=self.cases['mov32mi-upper']['expected']
        self.assertEqual((ordinary['input_evidence_count'],ordinary['observed_claims'],ordinary['required_claims']),
                         (33,30,36))
        for name in ('budget-e32-c64','budget-e64-c35','budget-e0-c0'):
            expected=self.cases[name]['expected']
            self.assertEqual(expected['conclusion'],'unknown')
            self.assertIsNone(expected['arithmetic'])
            self.assertTrue(expected['truncated'])
        self.assertEqual(self.cases['budget-e64-c35']['expected']['retained_claims'],31)
        self.assertEqual(self.cases['budget-e33-c64']['expected']['conclusion'],'consistent_with_evidence')
        self.assertEqual(self.cases['budget-e64-c36']['expected']['conclusion'],'consistent_with_evidence')
        maximum=self.cases['budget-max-bundle-e46-c49']['expected']
        self.assertEqual((maximum['input_evidence_count'],maximum['observed_claims'],maximum['required_claims']),
                         (46,43,49))
        self.assertEqual(maximum['conclusion'],'consistent_with_evidence')
        for name in ('budget-max-bundle-e45-c64','budget-max-bundle-e64-c48'):
            self.assertIsNone(self.cases[name]['expected']['arithmetic'])

    def test_synthetic_stream_and_context_bytes_independently(self):
        for name in ('mov32mi-upper','indexed-nonzero','wrong-operation','missing-integer',
                     'no-context','no-exception','rsp-sib-upper'):
            with self.subTest(case=name):
                row=self.cases[name]
                payload=oracle.build_synthetic_capture(row)
                signature,version,count,directory=struct.unpack_from('<4sIII',payload)
                self.assertEqual((signature,version),(b'MDMP',0xa793))
                streams={kind:(size,offset) for kind,size,offset in
                         (struct.unpack_from('<III',payload,directory+12*n) for n in range(count))}
                self.assertIn(5,streams)
                if name=='no-exception':
                    self.assertNotIn(6,streams)
                    continue
                size,offset=streams[6]
                self.assertEqual(size,168)
                self.assertEqual(struct.unpack_from('<I',payload,offset+8)[0],0xc0000005)
                operation,reported=struct.unpack_from('<QQ',payload,offset+40)
                self.assertEqual((operation,reported),(row['operation'],int(row['reported'],16)))
                context_size,context_offset=struct.unpack_from('<II',payload,offset+160)
                if name=='no-context':
                    self.assertEqual(context_size,0)
                else:
                    self.assertEqual(context_size,1232)
                    self.assertEqual(struct.unpack_from('<I',payload,context_offset+48)[0],row['context_flags'])
                    for register,field in [('rax',120),('rcx',128),('rsp',152)]:
                        self.assertEqual(struct.unpack_from('<Q',payload,context_offset+field)[0],
                                         int(row['registers'][register],16))

    def test_named_admission_controls_have_actual_conflicting_inputs(self):
        c=self.cases
        self.assertNotEqual(c['wrong-exception']['exception_code'],0xc0000005)
        self.assertEqual(c['execute']['operation'],8)
        self.assertNotEqual(c['wrong-operation']['operation'],c['wrong-operation']['decoded_receipt']['operation'])
        self.assertNotEqual(c['wrong-rip']['rip'],c['wrong-rip']['site'])
        self.assertNotEqual(c['wrong-exception-location']['exception_location'],c['wrong-exception-location']['site'])
        self.assertNotEqual(c['chained-record']['chain'],0)
        self.assertNotEqual(c['unknown-flags']['exception_flags']&~1,0)
        self.assertNotEqual(c['wrong-context-architecture']['context_flags']&0x00ff0000,0x00100000)
        self.assertFalse(c['missing-control']['context_flags']&1)
        self.assertFalse(c['missing-integer']['context_flags']&2)
        self.assertFalse(c['no-context']['context_present'])
        self.assertFalse(c['no-exception']['exception_present'])
        self.assertIsNotNone(c['indexed-zero']['decoded_receipt']['index'])
        self.assertEqual(int(c['indexed-zero']['registers']['rcx'],16),0)
        self.assertEqual(c['index-only']['decoded_receipt']['base'],None)
        self.assertEqual(c['absolute']['decoded_receipt']['base'],None)
        self.assertTrue(c['rip-relative']['decoded_receipt']['rip_relative'])
        self.assertEqual(c['address-size']['decoded_receipt']['address_width'],32)
        self.assertEqual(c['segment-fs']['decoded_receipt']['segment'],'fs')

    def test_invalid_parameter_count_is_a_binding_error_before_budgets(self):
        for evidence,claims in ((64,64),(0,0)):
            for count in (16,-1,True):
                with self.subTest(evidence=evidence,claims=claims,count=count):
                    row=copy.deepcopy(self.cases['mov32mi-upper'])
                    row.update(parameter_count=count,max_evidence=evidence,max_claims=claims)
                    with self.assertRaisesRegex(ValueError,'invalid-parameter-count'):
                        oracle.expected(row)
                    with self.assertRaisesRegex(ValueError,'invalid-parameter-count'):
                        oracle.build_synthetic_capture(row)

    def test_verified_receipt_absence_and_selected_prefix_are_separate_from_worksheet(self):
        for name in ('operand-size','vector','repeat','lock'):
            row=self.cases[name]
            self.assertFalse(row['receipt'])
            self.assertEqual(row['expected']['retained_evidence_count'],32)
            self.assertEqual(row['expected']['retained_claims'],31)
            self.assertIsNone(row['expected']['arithmetic'])
            self.assertEqual(row['expected']['conclusion'],'unknown')
            self.assertIn('missing-decoded-address-reference',row['expected']['required_gaps'])
        for name,opcode,prefix in [('repeat','XRELEASE_PREFIX','f3'),('lock','LOCK_PREFIX','f0')]:
            row=self.cases[name]
            self.assertTrue(row['code'].startswith(prefix))
            self.assertGreater(len(row['code'])//2,1)
            self.assertEqual(row['decoded_receipt']['opcode'],'MOV32mi')
            self.assertEqual((row['selected_instruction']['opcode'],row['selected_instruction']['bytes_hex'],
                              row['selected_instruction']['length']),(opcode,prefix,1))
            self.assertEqual(row['selected_instruction']['memory_access_shapes'],[])
            self.assertEqual(row['selected_instruction']['semantic_control'],'Stop')

    def test_receipt_and_numeric_negative_controls(self):
        corrupted=copy.deepcopy(self.records)
        corrupted['manifest.json']['cases'][0]['decoded_receipt']['signed_displacement']=17
        with self.assertRaises(AssertionError):
            oracle.validate_artifacts(corrupted)
        for number in ('+1','01','-0',' 1','1 ','','18446744075857035263','-2147483649'):
            with self.subTest(number=number):
                canonical=(number=='0' or number[0:1] in '123456789' and number.isdecimal()
                           or number.startswith('-') and number[1:2] in '123456789' and number[1:].isdecimal())
                allowed=canonical and -2147483648<=int(number)<=18446744075857035262
                self.assertFalse(allowed)
        changed=copy.deepcopy(self.records)
        changed['manifest.json']['cases'][0]['expected']['arithmetic']['effective_address']='0x0000000000000009'
        with self.assertRaises(AssertionError):
            oracle.validate_artifacts(changed)


